"""
Run every experiment, regenerate every figure, and write RESULTS.md.

    python -m experiments.run_all            # full run, about a minute
    python -m experiments.run_all --quick    # fewer paths, a few seconds
    python -m experiments.run_all --live SPY # use today's SPY option chain for the vol surface
"""

import argparse
import time

from experiments import _style as st
from experiments import convergence, greeks_check, hedge_frequency, iv_surface, transaction_costs, vol_mismatch


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true")
    parser.add_argument("--live", metavar="TICKER")
    args = parser.parse_args()

    start = time.time()
    print("1/6 convergence");      conv = convergence.run(args.quick)
    print("2/6 greeks");           grk = greeks_check.run(args.quick)
    print("3/6 implied vol");      ivs = iv_surface.run(args.quick, live_ticker=args.live)
    print("4/6 hedge frequency");  hf = hedge_frequency.run(args.quick)
    print("5/6 vol mismatch");     vm = vol_mismatch.run(args.quick)
    print("6/6 transaction costs"); tc = transaction_costs.run(args.quick)

    lines = ["# Results", "", f"Generated by `python -m experiments.run_all{' --quick' if args.quick else ''}`.", ""]

    lines += ["## 1. Convergence", "",
              f"* Black-Scholes call (S=K=100, T=1, r=5%, vol=20%): **{conv['bs_price']:.4f}**",
              f"* CRR tree error at 1,000 steps: {conv['tree_error_1000']:.5f}; fitted error slope "
              f"{conv['tree_slope']:.2f} (theory -1)",
              f"* Monte Carlo standard-error slope {conv['mc_slope']:.2f} (theory -0.5)",
              f"* Variance reduction at 100k paths: antithetic **{conv['variance_reduction_antithetic']:.1f}x**, "
              f"antithetic + control variate **{conv['variance_reduction_antithetic_cv']:.0f}x**", "",
              f"![]({'figures/' + conv['figure']})", ""]

    lines += ["## 2. Greeks", "", f"Worst relative gap between analytic and finite-difference Greeks: "
              f"{grk['worst_relative_fd_error']:.1e}", "", greeks_check.table_markdown(grk["table"]), "",
              f"![]({'figures/' + grk['figure']})", ""]

    lines += ["## 3. Implied volatility surface", "", f"* Source: {ivs['source']}; "
              f"{ivs['n_used']} out-of-the-money quotes used from {ivs['n_quotes']}",
              f"* ATM vol by months to expiry: {ivs['atm_vol_by_months']}",
              f"* Skew (vol points per 10% lower strike): {ivs['skew_by_months']}"]
    if "max_abs_vol_error_pts" in ivs:
        lines.append(f"* Solver recovered the true smile from noisy quotes to within "
                     f"{ivs['max_abs_vol_error_pts']:.3f} vol points (median {ivs['median_abs_vol_error_pts']:.4f})")
    lines += ["", f"![]({'figures/' + ivs['figure']})", ""]

    lines += ["## 4. Hedging frequency (realised vol = implied vol = 20%)", "",
              f"Premium for the 3-month ATM call: ${hf['premium']:.2f}. Fitted slope of std vs N: "
              f"{hf['slope']:.3f} (theory -0.5). Largest gap to Derman-Kamal: {100 * hf['max_ratio_error']:.1f}%. "
              f"Correlation of daily-hedged P&L with the theta-gamma prediction: {hf['gamma_corr_daily']:.3f}.", "",
              "| Rebalances | Mean P&L | Std P&L | Derman-Kamal |", "|---:|---:|---:|---:|"]
    lines += [f"| {n} | {m:+.4f} | {s:.4f} | {t:.4f} |" for n, m, s, t in hf["table"]]
    lines += ["", f"![]({'figures/' + hf['figure']})", ""]

    lines += ["## 5. Realised vs implied vol (sold at 20%, rebalanced 252 times)", "",
              "| Realised vol | BS(20%) - BS(realised) | Mean, hedge at implied | Std | Mean, hedge at realised | Std |",
              "|---:|---:|---:|---:|---:|---:|"]
    lines += [f"| {100 * r['sigma_r']:.0f}% | {r['theory']:+.3f} | {r['imp_mean']:+.3f} | {r['imp_std']:.3f} | "
              f"{r['real_mean']:+.3f} | {r['real_std']:.3f} |" for r in vm["rows"]]
    lines += ["", f"![]({'figures/' + vm['figure']})", ""]

    lines += ["## 6. Transaction costs", "",
              "Best rebalancing count (lowest root-mean-square P&L) by cost per side: "
              + ", ".join(f"{bp} bp -> {n}" for bp, n in tc["best_n"].items()), "",
              "| Cost | Rebalances | Leland vol | Mean P&L, priced at 20% | Mean P&L, Leland | Mean cost |",
              "|---:|---:|---:|---:|---:|---:|"]
    lines += [f"| {r['cost_bp']} bp | {r['n']} | {100 * r['leland_vol']:.2f}% | {r['mean_plain']:+.4f} | "
              f"{r['mean_leland']:+.4f} | {r['mean_cost']:.4f} |" for r in tc["leland"]]
    lines += ["", f"![]({'figures/' + tc['figure']})", ""]

    (st.ROOT / "RESULTS.md").write_text("\n".join(lines))
    print(f"done in {time.time() - start:.0f}s -> RESULTS.md and figures/")


if __name__ == "__main__":
    main()
